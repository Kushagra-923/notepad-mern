import { scenario, signup, newNote, type } from './helpers.mjs'

export default () => scenario('Teams', 5092, async ({ url, check, newPage }) => {
  const a = await newPage(), b = await newPage(), c = await newPage()
  await signup(b, url, 'bob')
  await signup(c, url, 'carol')
  await signup(a, url, 'alice')

  await a.getByRole('button', { name: '+ teams' }).click()
  await a.getByPlaceholder('New team name').fill('Physics group')
  await a.getByRole('button', { name: 'Create' }).click()
  await a.locator('.team-head', { hasText: 'Physics group' }).waitFor()
  await a.getByPlaceholder('Add member by username').fill('ghost')
  await a.getByRole('button', { name: 'Add', exact: true }).click()
  await a.getByText('No user named "ghost"').waitFor({ timeout: 5000 })
  check('adding an unknown user shows an error', true)
  await a.getByPlaceholder('Add member by username').fill('bob')
  await a.getByRole('button', { name: 'Add', exact: true }).click()
  await a.locator('.team .share-list li', { hasText: 'bob' }).waitFor()
  check('alice added bob to the team', true)
  await a.locator('.dialog').getByRole('button', { name: 'close' }).click()

  await a.locator('.tabs').getByRole('button', { name: 'Physics group' }).click()
  await newNote(a, 'New team note')
  await a.locator('.title').fill('Lab 3 results')
  await type(a, 'Measured g = 9.79')
  await a.getByText('Saved').waitFor()
  check('team note shows the team notice', await a.locator('.notice', { hasText: 'Team note' }).isVisible())

  await b.reload()
  await b.locator('.tabs').getByRole('button', { name: 'Physics group' }).click()
  await b.locator('aside li', { hasText: 'Lab 3 results' }).click()
  await b.locator('.tiptap').getByText('Measured g').waitFor()
  await b.locator('.tabs').getByRole('button', { name: 'shared with me' }).click()
  check('team note also appears under "shared with me" for bob', await b.locator('aside li', { hasText: 'Lab 3 results' }).isVisible())
  await b.locator('.tabs').getByRole('button', { name: 'Physics group' }).click()
  check('bob (member) can edit the team note', (await b.locator('.tiptap').getAttribute('contenteditable')) === 'true')
  check('bob has no delete or share button', (await b.getByRole('button', { name: 'delete' }).count()) === 0 && (await b.getByRole('button', { name: 'share', exact: true }).count()) === 0)
  await type(b, ' Bob: error margin 0.02')
  await b.getByText('Saved').waitFor()
  await a.waitForFunction(() => document.querySelector('.tiptap')?.textContent.includes('Bob: error'), null, { timeout: 12000 })
  check("alice sees bob's team edit live", true)

  await c.reload()
  check('carol (outsider) sees no team', (await c.locator('.tabs').getByRole('button', { name: 'Physics group' }).count()) === 0)

  await a.locator('.tabs').getByRole('button', { name: 'mine' }).click()
  await newNote(a)
  await a.locator('.title').fill('Personal draft')
  await type(a, 'to move')
  await a.getByText('Saved').waitFor()
  await a.getByRole('button', { name: 'share', exact: true }).click()
  await a.locator('.team-row select').selectOption({ label: 'Physics group' })
  await a.locator('.team-note').waitFor()
  await a.locator('.dialog').getByRole('button', { name: 'close' }).click()
  await b.locator('aside li', { hasText: 'Personal draft' }).waitFor({ timeout: 20000 })
  check('a note moved into the team appears for bob', true)

  await b.getByRole('button', { name: '+ teams' }).click()
  b.once('dialog', (d) => d.accept())
  await b.locator('.team .share-list li', { hasText: 'bob (you)' }).getByRole('button', { name: 'leave' }).click()
  await b.waitForTimeout(800)
  await b.locator('.dialog').getByRole('button', { name: 'close' }).click()
  check('after leaving, bob loses the team tab and its notes', (await b.locator('.tabs').getByRole('button', { name: 'Physics group' }).count()) === 0 && (await b.locator('aside li', { hasText: 'Lab 3 results' }).count()) === 0)
})
